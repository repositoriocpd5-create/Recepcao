insert into public.servidor_setor_vinculos (servidor_id, setor_id)
select distinct servidor.id, setor.id
from vinculos
join public.departamentos departamento on departamento.nome = vinculos.departamento_nome
join public.setores setor on setor.departamento_id = departamento.id and setor.nome = vinculos.setor_nome
join public.servidores servidor on upper(trim(servidor.nome)) = upper(trim(vinculos.servidor_nome))
on conflict do nothing;

